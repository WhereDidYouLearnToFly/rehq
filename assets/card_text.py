#!/usr/bin/env python3
"""Card text for the Spectrum build: the source of truth, plus the emitter.

The rules text on the printed cards is far too long for a 32 column screen in an
8x8 font, so each card is reworded here to the shortest wording that keeps the
rule exact. Text is stored as sentences, not as pre-broken lines, so changing
--width re-wraps everything instead of needing a rewrite.

Only characters the HeroQuest font can actually draw are allowed: A-Z, 0-9,
space and . , ! ' ? = -- everything else in that font's punctuation range is
artwork (monster faces, map tiles), so a stray colon or hyphen would print a
goblin. emit() refuses to write a file that breaks this.

Usage:
    python card_text.py                  # -> card_text.asm at 32 columns
    python card_text.py --width 22       # narrower panel
    python card_text.py --preview        # also render it in the real font
"""


import textwrap

# Hero classes, as bits, so a card can carry who may use it.
BARBARIAN, DWARF, ELF, WIZARD = 1, 2, 4, 8
ALL = BARBARIAN | DWARF | ELF | WIZARD
NOT_WIZARD = ALL & ~WIZARD

FONT = "../../hq-original/gfx8/hq_font_ascii.bin"

# The font draws these and nothing else. Anything outside prints as artwork.
LEGAL = set(" ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!'?=")

# id, title, body, price in gold (0 = not for sale), who may use it
